#!/usr/bin/env python3
"""
Slice a 4×3 icon sprite sheet into 12 individual transparent-BG PNGs.

The sheet is generated by ChatGPT image-2.0 with chunky pixel-art icons,
solid black on white background, with thin gray gridlines between cells.

Pipeline per cell:
  1. Crop the cell from the equal-grid division of the source image.
  2. Threshold: any pixel with R+G+B > 600 becomes transparent (drops the
     white BG and the light gray gridlines, keeps only the black icon).
  3. Find the bounding box of the remaining (black) pixels.
  4. Crop tight to that bbox, then re-pad with a fixed 8% margin on each
     side so all icons share the same "padding inside cell" feel.
  5. Resize to a uniform 256×256 output (clean integer downscale targets:
     16, 32, 64, 128 — works for any frame size we'd render at).
  6. Save with the named filename matching the SF Symbol it replaces.

Output filenames intentionally mirror SF Symbol conventions so the
SwiftUI swap is a 1-line `Image(systemName: "shuffle")` →
`DialIcon("shuffle")` substitution per call site.
"""

from __future__ import annotations

import sys
from pathlib import Path
from PIL import Image

ICON_NAMES = [
    # Row 1: status bar + brand
    "clock.arrow.circlepath", "chart.bar.fill", "info.circle", "flame.fill",
    # Row 2: transport (solid glyphs that go inside gel pills)
    "backward.fill", "play.fill", "pause.fill", "forward.fill",
    # Row 3: transport modifiers + badge marker
    "shuffle", "repeat", "repeat.1", "triangle.fill",
]

OUTPUT_SIZE = 256       # final square output edge
PAD_FRACTION = 0.08     # 8% margin inside the output square
WHITE_THRESHOLD = 600   # R+G+B above this → background → transparent


def to_alpha(img: Image.Image) -> Image.Image:
    """Convert white/light-gray BG to alpha=0, keep dark pixels opaque."""
    img = img.convert("RGBA")
    pixels = img.load()
    w, h = img.size
    for y in range(h):
        for x in range(w):
            r, g, b, _ = pixels[x, y]
            if r + g + b > WHITE_THRESHOLD:
                pixels[x, y] = (0, 0, 0, 0)
            else:
                # Force fully opaque black — the source is anti-aliased
                # in places (esp. the curved arrows), and tinting via
                # SwiftUI's template-image system needs a clean alpha mask
                # rather than partial-alpha gray.
                pixels[x, y] = (0, 0, 0, 255)
    return img


def tight_bbox(img: Image.Image) -> Image.Image | None:
    """Crop to the bounding box of opaque pixels. None if the cell is empty."""
    bbox = img.getbbox()
    if bbox is None:
        return None
    return img.crop(bbox)


def fit_to_square(img: Image.Image, size: int, pad: float) -> Image.Image:
    """Center the icon inside a `size`×`size` transparent canvas with
    `pad` fraction of margin on whichever axis is the limiting one."""
    inner = int(size * (1 - 2 * pad))
    w, h = img.size
    scale = inner / max(w, h)
    new_w, new_h = max(1, int(w * scale)), max(1, int(h * scale))
    resized = img.resize((new_w, new_h), Image.NEAREST)  # crisp pixel scaling
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ox = (size - new_w) // 2
    oy = (size - new_h) // 2
    canvas.paste(resized, (ox, oy), resized)
    return canvas


def main() -> int:
    if len(sys.argv) < 3:
        print("usage: slice-icon-sheet.py <input.png> <output_dir>", file=sys.stderr)
        return 1

    src = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    sheet = Image.open(src).convert("RGB")
    sheet_w, sheet_h = sheet.size
    cols, rows = 4, 3
    cell_w = sheet_w // cols
    cell_h = sheet_h // rows

    print(f"sheet: {sheet_w}×{sheet_h}, cell: {cell_w}×{cell_h}")

    for row in range(rows):
        for col in range(cols):
            idx = row * cols + col
            name = ICON_NAMES[idx]
            cell_box = (col * cell_w, row * cell_h, (col + 1) * cell_w, (row + 1) * cell_h)
            cell = sheet.crop(cell_box)
            keyed = to_alpha(cell)
            cropped = tight_bbox(keyed)
            if cropped is None:
                print(f"  [{idx:2d}] {name}: EMPTY (skipped)")
                continue
            final = fit_to_square(cropped, OUTPUT_SIZE, PAD_FRACTION)
            out_path = out_dir / f"{name}.png"
            final.save(out_path, "PNG")
            print(f"  [{idx:2d}] {name}: {cropped.size} → {OUTPUT_SIZE}×{OUTPUT_SIZE} → {out_path.name}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
